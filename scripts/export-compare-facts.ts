// ============================================================================
// export-compare-facts.ts: write the backend's update-compare-facts-2026-11-22.js
//
// Adds the compare-page upgrade of 2026-11-22 to Admin > Website > Compare, without
// overwriting anything an admin has edited:
//   - the shared headings for the new sections (glanceTitle, glanceUs, chooseThemTitle), only where missing
//   - per page: the "at a glance" table and "may suit you better" points, only where empty;
//     the competitor source (note, link, checked date), only where no link is set;
//     the new FAQs, only those whose question isn't there yet
// Built-in text is read from this repo (content/compare).
//
// Usage: node scripts/export-compare-facts.cjs --out <backend>/scripts/update-compare-facts-2026-11-22.js
// ============================================================================

import fs from "node:fs";
import { COMPARE_DEFAULTS, COMPARE_SLUG } from "@/content/compare/editable";

const i = process.argv.indexOf("--out");
const outFile = i > -1 ? process.argv[i + 1] : undefined;
if (!outFile) throw new Error("--out <file> is required");

const shared = { glanceTitle: COMPARE_DEFAULTS.glanceTitle, glanceUs: COMPARE_DEFAULTS.glanceUs, chooseThemTitle: COMPARE_DEFAULTS.chooseThemTitle };
const pages = COMPARE_DEFAULTS.pages
  .filter((p) => p.glance.length)
  .map((p) => ({
    slug: p.slug,
    glance: p.glance,
    chooseThem: p.chooseThem,
    competitorNote: p.competitorNote,
    competitorNoteSource: p.competitorNoteSource,
    competitorNoteChecked: p.competitorNoteChecked,
    faqs: p.faqs,
  }));

const script = `// update-compare-facts-2026-11-22.js (generated by the website's scripts/export-compare-facts.cjs)
// Compare pages: adds the "at a glance" table, the "may suit you better" points, the
// competitor source and the new FAQs to Admin > Website > Compare. Only fills what is
// empty or missing; nothing an admin wrote is replaced. Pages stay as drafts.
// Safe to run twice. The entry is copied to the "backups" collection first.
//
// DRY RUN by default. Set APPLY = true to write.
// Run: docker exec -i lms-landing-mongo mongosh --quiet "<DB_URL with localhost>" < update-compare-facts-2026-11-22.js
const APPLY = false;

const SLUG = ${JSON.stringify(COMPARE_SLUG.slug)};
const SHARED = ${JSON.stringify(shared, null, 2)};
const PAGES = ${JSON.stringify(pages, null, 2)};

(function () {
  const now = new Date();
  print("Database: " + db.getName() + (APPLY ? "   [APPLY]" : "   [DRY RUN: nothing is written]"));
  const doc = db.cms.findOne({ slug: SLUG });
  if (!doc || !doc.data) { print("   - no " + SLUG + " entry: the site uses its built-in pages, which already have everything. Nothing to do."); return; }
  const data = JSON.parse(JSON.stringify(doc.data));
  let changes = 0;
  Object.keys(SHARED).forEach((k) => {
    if (typeof data[k] === "string" && data[k].trim()) { print("   = same    " + k); }
    else { data[k] = SHARED[k]; changes++; print("   + add     " + k + ": " + SHARED[k]); }
  });
  const list = Array.isArray(data.pages) ? data.pages : [];
  PAGES.forEach((d) => {
    const p = list.find((x) => x && String(x.slug || "").trim().toLowerCase() === d.slug);
    if (!p) { print("   - skip    " + d.slug + " (not in the admin list)"); return; }
    if (!Array.isArray(p.glance) || !p.glance.length) { p.glance = d.glance; changes++; print("   + add     " + d.slug + ": table, " + d.glance.length + " rows"); }
    else print("   = same    " + d.slug + ": table already there");
    if (!Array.isArray(p.chooseThem) || !p.chooseThem.length) { p.chooseThem = d.chooseThem; changes++; print("   + add     " + d.slug + ": " + d.chooseThem.length + " 'may suit you better' points"); }
    if (!String(p.competitorNoteSource || "").trim()) {
      p.competitorNote = d.competitorNote; p.competitorNoteSource = d.competitorNoteSource; p.competitorNoteChecked = d.competitorNoteChecked;
      changes++; print("   + add     " + d.slug + ": source " + d.competitorNoteSource);
    }
    const faqs = Array.isArray(p.faqs) ? p.faqs : (p.faqs = []);
    const have = faqs.map((f) => String((f && f.question) || "").trim().toLowerCase());
    d.faqs.forEach((f) => {
      if (have.indexOf(f.question.trim().toLowerCase()) === -1) { faqs.push(f); changes++; print("   + add     " + d.slug + ": FAQ " + f.question); }
    });
  });
  if (!changes) { print("   Nothing to change."); return; }
  if (APPLY) {
    db.backups.insertOne({ collection: "cms", slug: doc.slug, savedAt: now, reason: "update-compare-facts-2026-11-22", doc });
    db.cms.updateOne({ _id: doc._id }, { $set: { data: data, updatedAt: now } });
    print("   Saved " + changes + " change(s).");
  }
})();
print(APPLY ? "\\nDone. Review the pages in Admin > Website > Compare before switching them on." : "\\nDry run only. Set APPLY = true at the top to write.");
`;
fs.writeFileSync(outFile, script);
console.log("Wrote " + outFile + " (" + pages.length + " pages)");
