// ============================================================================
// export-new-sections.ts: write the backend's add-new-sections-2026-11-19.js
//
// Makes the sections added on 2026-11-19 editable on a database that already has
// the v5 text (the live one), without touching anything an admin has edited:
//   - creates the new entries: Home: Mobile apps, Home: Sell and grow, Platform: Mobile apps
//   - adds the mobile app band fields (app*) to each Solutions page, only where missing
//   - appends the new cards to Platform: Sell (cards 7-9) and Platform: Brand (card 7),
//     only when the entry has fewer cards than the site now shows
//   - Site navigation: replaces the old site's flat menu (which the v5 site ignores) with the
//     current menu and footer columns, so they become editable. Skipped once it has dropdowns.
// Built-in text is read from this repo, so the admin starts with what the site shows.
//
// Usage: node scripts/export-new-sections.cjs --out <backend>/scripts/add-new-sections-2026-11-19.js
// ============================================================================

import fs from "node:fs";
import { HOME_DEFAULTS, HOME_SLUGS } from "@/content/home-sections";
import { PLATFORM_PAGES, platformDefaults } from "@/content/platform/editable";
import { SOLUTION_PAGES, solutionDefaults, type SolutionKey } from "@/content/solutions/editable";
import { navDefaults, SITE_NAV_SLUG } from "@/content/navigation-editable";

const i = process.argv.indexOf("--out");
const outFile = i > -1 ? process.argv[i + 1] : undefined;
if (!outFile) throw new Error("--out is required");

const clone = <T>(v: T): T => JSON.parse(JSON.stringify(v));

const create = [
  { slug: HOME_SLUGS.mobile.slug, pageSlug: "home", cmsTitle: HOME_SLUGS.mobile.label, title: "Mobile apps", fields: ["data"], data: clone(HOME_DEFAULTS.mobile) },
  { slug: HOME_SLUGS.sell.slug, pageSlug: "home", cmsTitle: HOME_SLUGS.sell.label, title: "Sell and grow", fields: ["data"], data: clone(HOME_DEFAULTS.sell) },
  {
    slug: PLATFORM_PAGES["mobile-app"].slug,
    pageSlug: "platform",
    cmsTitle: PLATFORM_PAGES["mobile-app"].label,
    title: "Mobile apps",
    fields: ["data"],
    data: clone(platformDefaults("mobile-app")),
  },
];

const addFields = (Object.keys(SOLUTION_PAGES) as SolutionKey[]).map((k) => {
  const d = solutionDefaults(k);
  return { slug: SOLUTION_PAGES[k].slug, data: { appTitle: d.appTitle, appText: d.appText, appPoints: d.appPoints, appAlertTitle: d.appAlertTitle, appAlertBody: d.appAlertBody } };
});

const siteNav = { slug: SITE_NAV_SLUG.slug, cmsTitle: SITE_NAV_SLUG.label, data: clone(navDefaults()) };

const appendCards = (["sell", "brand"] as const).map((k) => ({ slug: PLATFORM_PAGES[k].slug, cards: clone(platformDefaults(k).cards) }));

const script = `// add-new-sections-2026-11-19.js (generated by the frontend's scripts/export-new-sections.cjs)
// Makes the sections added on 2026-11-19 editable in the admin, without changing anything already edited:
//   1. Creates: Home: Mobile apps, Home: Sell and grow, Platform: Mobile apps (skipped if they exist)
//   2. Solutions pages: adds the mobile app band fields (app*) where they are missing
//   3. Platform: Sell and Platform: Brand: appends the new cards when the entry has fewer than the site shows
//   4. Site navigation: replaces the old flat menu (unused by the v5 site) with the current menu and footer columns
// Every changed document is copied to the "backups" collection first. Safe to run twice.
//
// DRY RUN by default. Set APPLY = true to write.
// Run: docker exec -i lms-landing-mongo mongosh --quiet "<DB_URL with localhost>" < add-new-sections-2026-11-19.js
const APPLY = false;

const CREATE = ${JSON.stringify(create, null, 2)};
const ADD_FIELDS = ${JSON.stringify(addFields, null, 2)};
const APPEND_CARDS = ${JSON.stringify(appendCards, null, 2)};
const SITE_NAV = ${JSON.stringify(siteNav, null, 2)};

const now = new Date();
const backup = (doc) => { if (APPLY) db.backups.insertOne({ collection: "cms", slug: doc.slug, savedAt: now, reason: "add-new-sections-2026-11-19", doc }); };
print("Database: " + db.getName() + (APPLY ? "   [APPLY]" : "   [DRY RUN: nothing is written]"));

print("\\n1. New entries");
CREATE.forEach((e) => {
  if (db.cms.findOne({ slug: e.slug })) { print("   = exists  " + e.slug); return; }
  print("   + create  " + e.slug + "  (" + e.cmsTitle + ")");
  if (APPLY) {
    db.cms.insertOne(Object.assign({}, e, { isActive: true, isDeleted: false, createdAt: now, updatedAt: now }));
    db.backups.insertOne({ collection: "cms", slug: e.slug, savedAt: now, created: true, reason: "add-new-sections-2026-11-19" });
  }
});

print("\\n2. Solutions: mobile app band fields");
ADD_FIELDS.forEach((e) => {
  const doc = db.cms.findOne({ slug: e.slug });
  if (!doc) { print("   - missing " + e.slug + " (the site uses its built-in text)"); return; }
  const data = doc.data || {};
  const set = {};
  Object.keys(e.data).forEach((k) => { if (!(k in data)) set["data." + k] = e.data[k]; });
  const keys = Object.keys(set);
  if (!keys.length) { print("   = same    " + e.slug); return; }
  print("   + fields  " + e.slug + ": " + keys.map((k) => k.slice(5)).join(", "));
  if (APPLY) { backup(doc); set.updatedAt = now; db.cms.updateOne({ _id: doc._id }, { $set: set }); }
});

print("\\n3. Platform: new cards");
APPEND_CARDS.forEach((e) => {
  const doc = db.cms.findOne({ slug: e.slug });
  if (!doc) { print("   - missing " + e.slug + " (the site uses its built-in text)"); return; }
  const cards = (doc.data && Array.isArray(doc.data.cards)) ? doc.data.cards : [];
  if (cards.length >= e.cards.length) { print("   = same    " + e.slug + " (" + cards.length + " cards)"); return; }
  const extra = e.cards.slice(cards.length);
  print("   + cards   " + e.slug + ": " + extra.map((c) => c.title).join(" | "));
  if (APPLY) { backup(doc); db.cms.updateOne({ _id: doc._id }, { $set: { "data.cards": cards.concat(extra), updatedAt: now } }); }
});

print("\\n4. Site navigation: top menu and footer columns");
(function () {
  const doc = db.cms.findOne({ slug: SITE_NAV.slug });
  if (!doc) {
    print("   + create  " + SITE_NAV.slug);
    if (APPLY) {
      db.cms.insertOne({ slug: SITE_NAV.slug, pageSlug: "settings", cmsTitle: SITE_NAV.cmsTitle, title: "Site navigation", fields: ["data"], data: SITE_NAV.data, isActive: true, isDeleted: false, createdAt: now, updatedAt: now });
      db.backups.insertOne({ collection: "cms", slug: SITE_NAV.slug, savedAt: now, created: true, reason: "add-new-sections-2026-11-19" });
    }
    return;
  }
  const nav = (doc.data && Array.isArray(doc.data.marketingNav)) ? doc.data.marketingNav : [];
  const hasDropdowns = nav.some((i) => i && Array.isArray(i.children) && i.children.length);
  if (hasDropdowns) { print("   = same    " + SITE_NAV.slug + " (already the v5 menu)"); return; }
  print("   ~ replace " + SITE_NAV.slug + ": old flat menu (" + nav.map((i) => i && i.label).join(", ") + ") -> current menu and footer columns");
  if (APPLY) {
    backup(doc);
    db.cms.updateOne({ _id: doc._id }, { $set: { data: SITE_NAV.data, cmsTitle: SITE_NAV.cmsTitle, fields: ["data"], updatedAt: now } });
  }
})();

print(APPLY ? "\\nDone. The website picks up admin edits on the next save (or deploy)." : "\\nDry run only. Set APPLY = true at the top to write.");
`;
fs.writeFileSync(outFile, script);
console.log(`Wrote ${outFile}: ${create.length} new entries, ${addFields.length} Solutions pages, ${appendCards.length} card lists`);
