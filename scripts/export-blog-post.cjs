// Writes a backend mongosh script that adds one built-in blog post (content/blog/posts.ts)
// to Admin > Website > Blog, because once the blog is managed in the admin, built-in posts don't show.
// Usage: node scripts/export-blog-post.cjs <slug> <backend>/scripts/add-blog-<slug>.js
const path = require("path");
const fs = require("fs");
const root = path.join(__dirname, "..");
const { createJiti } = require(path.join(root, "node_modules/jiti"));
const jiti = createJiti(path.join(root, "index.js"), { alias: { "@": root } });
const [slug, out] = process.argv.slice(2);
if (!slug || !out) { console.error("Usage: node scripts/export-blog-post.cjs <slug> <out>"); process.exit(1); }
jiti.import("./content/blog/posts.ts").then(({ BLOG_POSTS, BLOG_META }) => {
  const p = BLOG_POSTS[slug];
  if (!p) throw new Error(`No built-in post "${slug}"`);
  const meta = BLOG_META[slug] || {};
  // External links open in a new tab, as the admin editor saves them
  const content = p.content.trim().replace(/<a href="(https:\/\/[^"]+)">/g, '<a href="$1" target="_blank" rel="noopener noreferrer">');
  const doc = {
    slug: p.slug, title: p.title, subtitle: p.subtitle, metaTitle: p.metaTitle, metaDescription: p.metaDescription,
    date: p.date, author: p.author, readingTime: "", category: meta.category || "", cover: meta.art || "lms", coverImage: "",
    content, faqs: p.faqs,
  };
  const js = `// Adds the blog post "${slug}" to Admin > Website > Blog (generated by the website's scripts/export-blog-post.cjs).
// Does nothing if a post with this slug already exists. Dry run by default; set APPLY = true to write.
// Run: docker exec -i lms-landing-mongo mongosh --quiet "$DB" < scripts/${path.basename(out)}
const APPLY = false;
(() => {
  const doc = ${JSON.stringify(doc, null, 2)};
  const existing = db.blogposts.findOne({ slug: doc.slug, isDeleted: { $ne: true } });
  if (existing) { print("A post with slug " + doc.slug + " already exists; nothing to do."); return; }
  print("Will add: " + doc.title + " (" + doc.date + ", " + doc.faqs.length + " FAQs, " + doc.content.length + " characters)");
  if (!APPLY) { print("Dry run. Set APPLY = true to add it."); return; }
  const now = new Date();
  db.blogposts.insertOne(Object.assign({}, doc, { isActive: true, isDeleted: false, createdAt: now, updatedAt: now, __v: 0 }));
  print("Added. To show it on the website now, run:");
  print("  docker exec -i lms-landing-backend node - blog < scripts/revalidate-frontend.js");
})();
`;
  fs.writeFileSync(out, js);
  console.log("Wrote", out);
}).catch((e) => { console.error(e); process.exit(1); });
