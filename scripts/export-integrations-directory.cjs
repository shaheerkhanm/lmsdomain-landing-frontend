// Writes a backend mongosh script that adds the integrations directory (and the homepage
// strip text) to Admin > Website > Integrations, and an "Integrations" link to the footer's
// Platform column in Admin > Settings > Site navigation. Fills only what is missing.
// Usage: node scripts/export-integrations-directory.cjs <backend>/scripts/update-integrations-directory-<date>.js
const path = require("path");
const fs = require("fs");
const root = path.join(__dirname, "..");
const { createJiti } = require(path.join(root, "node_modules/jiti"));
const jiti = createJiti(path.join(root, "index.js"), { alias: { "@": root } });
const out = process.argv[2];
if (!out) { console.error("Usage: node scripts/export-integrations-directory.cjs <out>"); process.exit(1); }
jiti.import("./content/integrations-editable.ts").then(({ INTEGRATIONS_DEFAULTS: D }) => {
  const add = {
    featuredEyebrow: D.featuredEyebrow, featuredTitle: D.featuredTitle,
    directoryEyebrow: D.directoryEyebrow, directoryTitle: D.directoryTitle, directorySubtitle: D.directorySubtitle,
    directory: D.directory,
    stripEyebrow: D.stripEyebrow, stripTitle: D.stripTitle, stripLink: D.stripLink,
  };
  const js = `// Adds the integrations directory to Admin > Website > Integrations and an "Integrations" link
// to the footer's Platform column. Generated by the website's scripts/export-integrations-directory.cjs.
// Fills only what is missing; never changes text you have edited. Backs up both entries first.
// Dry run by default; set APPLY = true to write.
// Run: docker exec -i lms-landing-mongo mongosh --quiet "$DB" < scripts/${path.basename(out)}
const APPLY = false;
(() => {
  const add = ${JSON.stringify(add, null, 2)};
  const now = new Date();
  const backups = db.getCollection("cms_backup_integrations");

  const intg = db.cms.findOne({ slug: "site-integration-pages" });
  if (!intg) { print("Admin > Website > Integrations doesn't exist yet: run add-integration-pages-2026-11-23.js first."); return; }
  const set = {};
  for (const k of Object.keys(add)) if (intg.data[k] === undefined || (Array.isArray(add[k]) && !(intg.data[k] || []).length)) set["data." + k] = add[k];
  print("Integrations: will add " + (Object.keys(set).length ? Object.keys(set).map((k) => k.slice(5)).join(", ") : "nothing (already there)")
    + ". Directory: " + add.directory.filter((x) => x.live).length + " live, " + add.directory.filter((x) => !x.live).length + " switched off (coming).");

  const nav = db.cms.findOne({ slug: "site-navigation" });
  let navSet = null;
  if (nav && nav.data && Array.isArray(nav.data.footerColumns)) {
    const cols = JSON.parse(JSON.stringify(nav.data.footerColumns));
    const platform = cols.find((c) => /platform/i.test(c.title || ""));
    const has = cols.some((c) => (c.links || []).some((l) => l.href === "/integrations"));
    if (platform && !has) {
      const i = platform.links.findIndex((l) => l.href === "/platform");
      platform.links.splice(i < 0 ? platform.links.length : i, 0, { title: "Integrations", href: "/integrations" });
      navSet = cols;
      print("Footer: will add Integrations to the " + platform.title + " column.");
    } else print("Footer: " + (has ? "already links to /integrations." : "no Platform column found; add the link in Admin > Settings > Site navigation."));
  } else print("Footer: no saved navigation in the admin; the website's built-in footer already has the link.");

  if (!APPLY) { print("Dry run. Set APPLY = true to write."); return; }
  if (Object.keys(set).length) { backups.insertOne({ slug: intg.slug, savedAt: now, doc: intg }); db.cms.updateOne({ _id: intg._id }, { $set: Object.assign(set, { updatedAt: now }) }); }
  if (navSet) { backups.insertOne({ slug: nav.slug, savedAt: now, doc: nav }); db.cms.updateOne({ _id: nav._id }, { $set: { "data.footerColumns": navSet, updatedAt: now } }); }
  print("Done. To show it on the website now, run:");
  print("  docker exec -i lms-landing-backend node - cms integrations navigation < scripts/revalidate-frontend.js");
})();
`;
  fs.writeFileSync(out, js);
  console.log("Wrote", out);
}).catch((e) => { console.error(e); process.exit(1); });
