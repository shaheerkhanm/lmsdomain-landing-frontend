// Writes a backend mongosh script that creates the Admin > Website > Integrations entry
// (site-integration-pages) from the built-in text (content/integrations-editable.ts).
// Usage: node scripts/export-integration-pages.cjs <backend>/scripts/add-integration-pages-<date>.js
const path = require("path");
const fs = require("fs");
const root = path.join(__dirname, "..");
const { createJiti } = require(path.join(root, "node_modules/jiti"));
const jiti = createJiti(path.join(root, "index.js"), { alias: { "@": root } });
const out = process.argv[2];
if (!out) { console.error("Usage: node scripts/export-integration-pages.cjs <out>"); process.exit(1); }
jiti.import("./content/integrations-editable.ts").then(({ INTEGRATIONS_DEFAULTS, INTEGRATIONS_SLUG }) => {
  const entry = {
    slug: INTEGRATIONS_SLUG.slug,
    pageSlug: "integration-pages",
    cmsTitle: INTEGRATIONS_SLUG.label,
    title: "Integration pages",
    data: INTEGRATIONS_DEFAULTS,
    fields: ["data"],
  };
  const js = `// Creates Admin > Website > Integrations (CMS entry ${entry.slug}) with the text the website shows today.
// Generated by the website's scripts/export-integration-pages.cjs. Does nothing if the entry already exists.
// Dry run by default; set APPLY = true to write.
// Run: docker exec -i lms-landing-mongo mongosh --quiet "$DB" < scripts/${path.basename(out)}
const APPLY = false;
(() => {
  const entry = ${JSON.stringify(entry, null, 2)};
  if (db.cms.findOne({ slug: entry.slug })) { print("Admin entry " + entry.slug + " already exists; nothing to do."); return; }
  print("Will add " + entry.slug + " with " + entry.data.pages.length + " integration pages: " + entry.data.pages.map((p) => p.name).join(", "));
  if (!APPLY) { print("Dry run. Set APPLY = true to add it."); return; }
  const now = new Date();
  db.cms.insertOne(Object.assign({}, entry, { isActive: true, isDeleted: false, createdAt: now, updatedAt: now }));
  print("Added. It appears in Admin > Website > Integrations. The website text is unchanged until you edit it there.");
})();
`;
  fs.writeFileSync(out, js);
  console.log("Wrote", out);
}).catch((e) => { console.error(e); process.exit(1); });
