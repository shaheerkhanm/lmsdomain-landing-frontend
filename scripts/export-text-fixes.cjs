// export-text-fixes.cjs: write the backend's fix-texts-2026-11-19.js from scripts/text-fixes-2026-11-19.json
// Usage: node scripts/export-text-fixes.cjs --out <backend>/scripts/fix-texts-2026-11-19.js
const fs = require("fs");
const path = require("path");
const i = process.argv.indexOf("--out");
const out = i > -1 ? process.argv[i + 1] : null;
if (!out) throw new Error("--out is required");
const j = process.argv.indexOf("--pairs");
const pairsFile = j > -1 ? process.argv[j + 1] : path.join(__dirname, "text-fixes-2026-11-19.json");
const { pairs } = JSON.parse(fs.readFileSync(pairsFile, "utf8"));

const script = `// fix-texts-2026-11-19.js (generated by the frontend's scripts/export-text-fixes.cjs)
// 1. Adds Admin > Pricing > "Pricing: Plans and prices source" (starts on "admin": nothing changes until it is switched).
// 2. Live classes: replaces Zoom-only wording with "live classes" (classes run on Zoom, Google Meet or Teams).
// 3. Custom domain is Growth and up (Starter: a free LMS Domain subdomain): fixes "own domain on every plan" texts,
//    and in Admin > Pricing: Starter's feature line, Growth's "Your own domain" line and the comparison row.
// Exact phrases only (${pairs.length} of them), in page text (cms), SEO and blog posts. Every changed document
// is copied to the "backups" collection first. Safe to run twice.
//
// DRY RUN by default. Set APPLY = true to write.
// Run: docker exec -i lms-landing-mongo mongosh --quiet "<DB_URL with localhost>" < fix-texts-2026-11-19.js
const APPLY = false;
const PAIRS = ${JSON.stringify(pairs, null, 2)};

const now = new Date();
const backup = (collection, doc) => { if (APPLY) db.backups.insertOne({ collection, slug: doc.slug || String(doc._id), savedAt: now, reason: "fix-texts-2026-11-19", doc }); };
print("Database: " + db.getName() + (APPLY ? "   [APPLY]" : "   [DRY RUN: nothing is written]"));

print("\\n1. Pricing source switch");
(function () {
  if (db.cms.findOne({ slug: "pricing-source" })) { print("   = exists  pricing-source"); return; }
  print("   + create  pricing-source (Pricing: Plans and prices source = admin)");
  if (!APPLY) return;
  db.cms.insertOne({ slug: "pricing-source", pageSlug: "pricing", cmsTitle: "Pricing: Plans and prices source", title: "Plans and prices source", fields: ["data"], data: { source: "admin" }, isActive: true, isDeleted: false, createdAt: now, updatedAt: now });
  db.backups.insertOne({ collection: "cms", slug: "pricing-source", savedAt: now, created: true, reason: "fix-texts-2026-11-19" });
})();

// Replace the phrases in every string inside a value; counts the replacements
function fix(value, hit) {
  if (typeof value === "string") {
    let s = value;
    for (const [a, b] of PAIRS) { if (s.indexOf(a) > -1) { hit.n += s.split(a).length - 1; s = s.split(a).join(b); } }
    return s;
  }
  if (Array.isArray(value)) return value.map((v) => fix(v, hit));
  if (value && typeof value === "object" && !(value instanceof Date) && !(value instanceof ObjectId)) {
    const o = {};
    for (const k of Object.keys(value)) o[k] = fix(value[k], hit);
    return o;
  }
  return value;
}

function sweep(collection, fields, label) {
  print("\\n" + label);
  let docs = 0, total = 0;
  db.getCollection(collection).find({ isDeleted: { $ne: true } }).forEach((doc) => {
    const hit = { n: 0 }, set = {};
    for (const f of fields) {
      if (!(f in doc)) continue;
      const next = fix(doc[f], hit);
      if (JSON.stringify(next) !== JSON.stringify(doc[f])) set[f] = next;
    }
    if (!hit.n || !Object.keys(set).length) return;
    docs++; total += hit.n;
    print("   ~ " + (doc.slug || doc.page || doc._id) + ": " + hit.n + " phrase" + (hit.n > 1 ? "s" : ""));
    if (APPLY) { backup(collection, doc); set.updatedAt = now; db.getCollection(collection).updateOne({ _id: doc._id }, { $set: set }); }
  });
  print("   " + (docs ? docs + " documents, " + total + " phrases" : "nothing to change"));
}
sweep("cms", ["title", "subTitle", "heading", "description", "content", "buttonText", "tags", "data"], "2. Page text (cms)");
sweep("seos", ["metatitle", "metadescription", "ogtitle", "ogdescription", "ogTitle", "ogDescription"], "   SEO (seos)");
sweep("blogposts", ["title", "subtitle", "metaTitle", "metaDescription", "content", "faqs"], "   Blog posts (blogposts)");

print("\\n3. Admin > Pricing: custom domain from Growth");
(function () {
  const doc = db.cms.findOne({ slug: "pricing-v2" });
  if (!doc || !doc.data || !Array.isArray(doc.data.plans)) { print("   - no pricing-v2 entry"); return; }
  const data = JSON.parse(JSON.stringify(doc.data));
  const notes = [];
  const starter = data.plans.find((p) => p && p.slug === "starter");
  const growth = data.plans.find((p) => p && p.slug === "growth");
  const SUB = "Free LMS Domain subdomain with SSL", OWN = "Your own domain with free SSL";
  if (starter && Array.isArray(starter.features)) {
    const k = starter.features.findIndex((f) => /own domain|custom domain/i.test(f));
    if (k > -1) { notes.push("Starter: \\"" + starter.features[k] + "\\" -> \\"" + SUB + "\\""); starter.features[k] = SUB; }
    else if (!starter.features.some((f) => /subdomain/i.test(f))) { starter.features.splice(1, 0, SUB); notes.push("Starter: + \\"" + SUB + "\\""); }
  }
  if (growth && Array.isArray(growth.features) && !growth.features.some((f) => /own domain|custom domain/i.test(f))) {
    growth.features.unshift(OWN); notes.push("Growth: + \\"" + OWN + "\\"");
  }
  (data.comparison || []).forEach((row) => {
    if (row && /custom domain/i.test(row.label || "") && row.values && row.values.starter === true) { row.values.starter = "Free subdomain"; notes.push("Comparison \\"" + row.label + "\\": Starter -> Free subdomain"); }
  });
  if (!notes.length) { print("   = same    pricing-v2"); return; }
  notes.forEach((n) => print("   ~ " + n));
  if (APPLY) { backup("cms", doc); db.cms.updateOne({ _id: doc._id }, { $set: { data, updatedAt: now } }); }
})();

print(APPLY ? "\\nDone. The website shows the new text on the next save (or deploy)." : "\\nDry run only. Set APPLY = true at the top to write.");
`;
fs.writeFileSync(out, script);
console.log("Wrote " + out + " (" + pairs.length + " phrases)");
